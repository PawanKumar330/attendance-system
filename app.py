@app.route("/api/attendance", methods=["POST"])
def submit_attendance() -> Any:
    """
    Accepts attendance data and writes it into the sheet.

    Target-Column Logic:
        1. Reads Row DATA_START_ROW (first student data row).
        2. Scans from column DATE_COL_START (H) rightward.
        3. The FIRST column that has no 'P' or 'A' in that row is the target.
        4. Writes the selected date as the header in HEADER_ROW of that column.
        5. Writes P/A for every student in that column (skips non-empty cells).
        6. Expands the sheet grid automatically if the column exceeds grid limits.
    """
    # ── 1. Parse & validate ───────────────────────────────────────────────────
    payload: dict = request.get_json(silent=True) or {}
    attendance_records: list[dict] = payload.get("attendance", [])
    selected_date: str = payload.get("date", "").strip()

    if not attendance_records:
        return jsonify({"error": "No attendance records provided."}), 400
    if not selected_date:
        return jsonify({"error": "No date selected. Please pick a date before submitting."}), 400

    # Convert YYYY-MM-DD → DD/MM/YYYY for the sheet header
    try:
        parsed_date = datetime.strptime(selected_date, "%Y-%m-%d")
        date_str = parsed_date.strftime("%d/%m/%Y")   # e.g. "18/07/2026"
    except ValueError:
        return jsonify({"error": f"Invalid date: '{selected_date}'. Expected YYYY-MM-DD."}), 400

    try:
        worksheet = _open_worksheet()

        # ── 2. Fetch entire sheet once ────────────────────────────────────────
        all_values: list[list[str]] = worksheet.get_all_values()

        if len(all_values) < DATA_START_ROW:
            return jsonify({"error": f"Sheet has fewer than {DATA_START_ROW} rows."}), 400

        # ── 3. Find target column by scanning the FIRST DATA ROW ─────────────
        # Read Row DATA_START_ROW (0-indexed: DATA_START_ROW - 1).
        # Start from DATE_COL_START (column H = index 7 in 0-based).
        # The first column whose cell is NOT 'P' / 'A' is our write target.
        first_data_row: list[str] = all_values[DATA_START_ROW - 1]

        target_col_idx: int | None = None
        col_scan = DATE_COL_START  # start from column H (1-based)
        while True:
            cell_0 = col_scan - 1   # 0-based index
            current_val = (
                first_data_row[cell_0].strip().upper()
                if cell_0 < len(first_data_row)
                else ""
            )
            if current_val not in ("P", "A"):
                target_col_idx = col_scan
                break
            col_scan += 1
            # Safety: stop at column 200 to prevent infinite loop
            if col_scan > 200:
                return jsonify({"error": "Could not find an empty attendance column (scanned up to column 200)."}), 500

        target_col_letter = _col_index_to_letter(target_col_idx)
        logger.info(
            "First empty attendance column: %d (%s).",
            target_col_idx, target_col_letter,
        )

        # ── 4. Expand sheet grid if needed ────────────────────────────────────
        if target_col_idx > worksheet.col_count:
            new_total = target_col_idx + 10
            worksheet.resize(cols=new_total)
            logger.info("Sheet grid expanded to %d columns.", new_total)

        # ── 5. Write the selected date into the header row ────────────────────
        date_cell = f"{target_col_letter}{HEADER_ROW}"
        worksheet.update_acell(date_cell, date_str)
        logger.info("Wrote date header '%s' to %s.", date_str, date_cell)

        # ── 6. Build student row-number lookup ────────────────────────────────
        row_lookup: dict[str, int] = {}   # roll → sheet row
        reg_lookup: dict[str, int] = {}   # reg  → sheet row

        for row_idx, row in enumerate(all_values[DATA_START_ROW - 1:], start=DATA_START_ROW):
            while len(row) < NAME_COL:
                row.append("")
            roll = row[ROLL_COL - 1].strip()
            reg  = row[REG_COL  - 1].strip()
            if roll:
                row_lookup[roll] = row_idx
            if reg:
                reg_lookup[reg] = row_idx

        # ── 7. Read current column values (to skip already-filled cells) ──────
        col_current: list[str] = worksheet.col_values(target_col_idx)

        # ── 8. Build batch update list ────────────────────────────────────────
        cells_to_update = []
        matched_count   = 0
        skipped_count   = 0
        unmatched_rolls = []

        for record in attendance_records:
            roll   = record.get("roll_no", "").strip()
            reg    = record.get("reg_no",  "").strip()
            status = record.get("status",  "A").strip().upper()
            if status not in ("P", "A"):
                status = "A"

            sheet_row = row_lookup.get(roll) or reg_lookup.get(reg)
            if sheet_row is None:
                logger.warning("No match for Roll='%s' / Reg='%s'.", roll, reg)
                unmatched_rolls.append(roll or reg)
                continue

            # Skip if this cell already has P or A
            existing = (
                col_current[sheet_row - 1].strip().upper()
                if sheet_row <= len(col_current) else ""
            )
            if existing in ("P", "A"):
                skipped_count += 1
                continue

            row_num, col_num = gspread.utils.a1_to_rowcol(
                f"{target_col_letter}{sheet_row}"
            )
            cells_to_update.append(gspread.Cell(row=row_num, col=col_num, value=status))
            matched_count += 1

        # ── 9. Single batch write ─────────────────────────────────────────────
        if cells_to_update:
            worksheet.update_cells(cells_to_update, value_input_option="USER_ENTERED")
            logger.info(
                "Wrote %d cells to col %s (skipped %d already-filled).",
                matched_count, target_col_letter, skipped_count,
            )

        # ── 10. Return summary ────────────────────────────────────────────────
        response = {
            "success":         True,
            "date_written":    date_str,
            "column_written":  target_col_letter,
            "is_new_column":   True,
            "matched_count":   matched_count,
            "skipped_count":   skipped_count,
            "total_submitted": len(attendance_records),
            "unmatched":       unmatched_rolls,
        }
        logger.info("Attendance done: %s", json.dumps(response))
        return jsonify(response), 200

    except RuntimeError as exc:
        logger.error("POST /api/attendance failed: %s", exc)
        return jsonify({"error": str(exc)}), 500
    except Exception as exc:
        logger.exception("Unexpected error in POST /api/attendance.")
        return jsonify({"error": f"An unexpected server error occurred: {exc}"}), 500





