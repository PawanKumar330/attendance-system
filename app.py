@app.route("/api/students", methods=["GET"])
def get_students() -> Any:
    """
    Reads all student records from the spreadsheet (Row 3 downwards) and
    returns a JSON array. Each element has the shape:
        { "roll_no": "...", "reg_no": "...", "name": "..." }

    Only rows that have at least a Roll No value are included; empty trailing
    rows are automatically skipped.
    """
    try:
        worksheet = _open_worksheet()

        # Fetch all values in the sheet once (single API call).
        all_values: list[list[str]] = worksheet.get_all_values()

        if len(all_values) < DATA_START_ROW:
            logger.warning("Sheet has fewer than %d rows — no student data.", DATA_START_ROW)
            return jsonify({"students": [], "count": 0})

        students = []
        for row_idx, row in enumerate(all_values[DATA_START_ROW - 1 :], start=DATA_START_ROW):
            # Pad short rows to avoid IndexError
            while len(row) < NAME_COL:
                row.append("")

            roll_no = row[ROLL_COL - 1].strip()
            reg_no  = row[REG_COL - 1].strip()
            name    = row[NAME_COL - 1].strip()

            # Skip entirely empty rows (trailing sheet rows)
            if not roll_no and not reg_no and not name:
                continue

            students.append(
                {
                    "roll_no": roll_no,
                    "reg_no":  reg_no,
                    "name":    name,
                }
            )

        logger.info("Fetched %d student records.", len(students))
        return jsonify({"students": students, "count": len(students)})

    except RuntimeError as exc:
        logger.error("GET /api/students failed: %s", exc)
        return jsonify({"error": str(exc)}), 500
    except Exception as exc:
        logger.exception("Unexpected error in GET /api/students.")
        return jsonify({"error": f"An unexpected error occurred: {exc}"}), 500


