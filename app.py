def _find_col_index(header_row_values: list[str], label: str) -> int | None:
    """
    Returns the 1-based column index for a given label within a header row list.
    Returns None if the label is not found.
    """
    for idx, cell_value in enumerate(header_row_values, start=1):
        if cell_value.strip() == label.strip():
            return idx
    return None


def _col_index_to_letter(col_index: int) -> str:
    """
    Converts a 1-based column index to its A1-notation letter(s).
    e.g. 1 → 'A', 26 → 'Z', 27 → 'AA'
    """
    result = ""
    while col_index > 0:
        col_index, remainder = divmod(col_index - 1, 26)
        result = chr(65 + remainder) + result
    return result


# Common date formats that may appear in a Google Sheet cell.
# strptime's %d / %m accept both zero-padded and non-padded values,
# so "%d/%m/%Y" matches both "18/07/2026" and "18/7/2026".
_DATE_FORMATS = [
    "%d/%m/%Y",   # 18/07/2026  (DD/MM/YYYY — new sheet format)
    "%m/%d/%Y",   # 07/18/2026  (M/D/YYYY  — old sheet format)
    "%Y-%m-%d",   # 2026-07-18
    "%d-%m-%Y",   # 18-07-2026
    "%Y/%m/%d",   # 2026/07/18
    "%d.%m.%Y",   # 18.07.2026
]


def _parse_date_cell(cell_value: str) -> datetime | None:
    """
    Attempts to parse a date string from a sheet cell into a datetime object.
    Tries multiple common formats so format variations don't cause mismatches.
    Returns None if the string cannot be parsed as any known date format.
    """
    v = cell_value.strip()
    if not v:
        return None
    for fmt in _DATE_FORMATS:
        try:
            return datetime.strptime(v, fmt)
        except ValueError:
            continue
    return None


