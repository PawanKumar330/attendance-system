def _get_gspread_client() -> gspread.Client:
    """
    Authenticates with Google APIs using the Service Account credentials
    stored in CREDENTIALS_FILE and returns an authorised gspread client.
    Raises a RuntimeError if the credentials file is missing or invalid.
    """
    try:
        creds = ServiceAccountCredentials.from_json_keyfile_name(
            CREDENTIALS_FILE, SCOPES
        )
        client = gspread.authorize(creds)
        logger.info("Successfully authenticated with Google Sheets API.")
        return client
    except FileNotFoundError:
        msg = (
            f"'{CREDENTIALS_FILE}' not found. Place your downloaded Service "
            "Account JSON key in the project root and rename it 'credentials.json'."
        )
        logger.error(msg)
        raise RuntimeError(msg)
    except Exception as exc:
        logger.exception("Failed to authenticate with Google Sheets API.")
        raise RuntimeError(f"Authentication error: {exc}") from exc


def _open_worksheet() -> gspread.Worksheet:
    """
    Opens the target spreadsheet by its ID (no Drive API needed) and returns
    the correct Worksheet object using the GID from the browser URL.
    """
    client = _get_gspread_client()
    try:
        spreadsheet = client.open_by_key(SPREADSHEET_ID)
        if WORKSHEET_GID is not None:
            # Find the worksheet whose id matches the GID in the URL
            worksheet = next(
                (ws for ws in spreadsheet.worksheets() if ws.id == WORKSHEET_GID),
                None,
            )
            if worksheet is None:
                raise RuntimeError(
                    f"No worksheet with GID {WORKSHEET_GID} found in spreadsheet {SPREADSHEET_ID}. "
                    "Check the #gid= value in your Google Sheets URL."
                )
        else:
            worksheet = spreadsheet.sheet1
        logger.info(
            "Opened worksheet '%s' (GID: %s) from spreadsheet ID '%s'.",
            worksheet.title,
            worksheet.id,
            SPREADSHEET_ID,
        )
        return worksheet
    except gspread.SpreadsheetNotFound:
        msg = (
            f"Spreadsheet ID '{SPREADSHEET_ID}' not found. "
            "Ensure the sheet has been shared with the service account email: "
            "attendance-bot@striker-auction.iam.gserviceaccount.com"
        )
        logger.error(msg)
        raise RuntimeError(msg)


